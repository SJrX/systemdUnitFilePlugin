package net.sjrx.intellij.plugins.systemdunitfiles.semanticdata.optionvalues.ai

import net.sjrx.intellij.plugins.systemdunitfiles.semanticdata.optionvalues.SimpleGrammarOptionValues
import net.sjrx.intellij.plugins.systemdunitfiles.semanticdata.optionvalues.grammar.EOF
import net.sjrx.intellij.plugins.systemdunitfiles.semanticdata.optionvalues.grammar.FlexibleLiteralChoiceTerminal
import net.sjrx.intellij.plugins.systemdunitfiles.semanticdata.optionvalues.grammar.SequenceCombinator

/*
 * [Link] Port= in a .link file.
 *
 * man    https://www.freedesktop.org/software/systemd/man/latest/systemd.link.html#Port=
 * parser https://github.com/systemd/systemd/blob/0f0682b773/src/shared/ethtool-util.c#L84   config_parse_port (0), DEFINE_CONFIG_PARSE_ENUM
 * leaf   https://github.com/systemd/systemd/blob/0f0682b773/src/shared/ethtool-util.c#L75-L81   port_table
 */

/**
 * Validator for `[Link] Port=` (.link).
 *
 * C function: config_parse_port, generated by DEFINE_CONFIG_PARSE_ENUM over port_table: exactly one of
 * `tp`, `aui`, `mii`, `fibre` or `bnc` (case-sensitive string-table lookup). An invalid value is
 * logged and ignored by udev.
 */
class ConfigParsePortOptionValue : SimpleGrammarOptionValues(
    "config_parse_port",
    SequenceCombinator(FlexibleLiteralChoiceTerminal("tp", "aui", "mii", "fibre", "bnc"), EOF())
)
