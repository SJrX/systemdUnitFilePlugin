/*
 * [Link] MACAddressPolicy= in a .link file.
 *
 * man    https://www.freedesktop.org/software/systemd/man/latest/systemd.link.html#MACAddressPolicy=
 * parser https://github.com/systemd/systemd/blob/0f0682b773/src/udev/net/link-config.c#L2145-L2149   config_parse_mac_address_policy (0), DEFINE_CONFIG_PARSE_ENUM_WITH_DEFAULT
 * leaf   https://github.com/systemd/systemd/blob/0f0682b773/src/udev/net/link-config.c#L2138-L2142   mac_address_policy_table
 */

/**
 * Validator for `[Link] MACAddressPolicy=` (.link).
 *
 * C function: config_parse_mac_address_policy, generated by DEFINE_CONFIG_PARSE_ENUM_WITH_DEFAULT over
 * mac_address_policy_table: exactly one of `persistent`, `random` or `none` (case-sensitive). An empty
 * assignment selects the default, `none`. An invalid value is logged and ignored by udev.
 */
class ConfigParseMacAddressPolicyOptionValue : SimpleGrammarOptionValues(
    "config_parse_mac_address_policy",
    SequenceCombinator(FlexibleLiteralChoiceTerminal("persistent", "random", "none"), EOF())
)
