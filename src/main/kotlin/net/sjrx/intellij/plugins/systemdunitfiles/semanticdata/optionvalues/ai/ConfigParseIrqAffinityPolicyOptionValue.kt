/**
 * Validator for `[Link] IRQAffinityPolicy=` (.link).
 *
 * C function: config_parse_irq_affinity_policy, generated by DEFINE_CONFIG_PARSE_ENUM_WITH_DEFAULT over
 * irq_affinity_policy_table: exactly `single` or `spread` (case-sensitive). An empty assignment unsets
 * it. An invalid value is logged and ignored by udev.
 */
class ConfigParseIrqAffinityPolicyOptionValue : SimpleGrammarOptionValues(
    "config_parse_irq_affinity_policy",
    SequenceCombinator(FlexibleLiteralChoiceTerminal("single", "spread"), EOF())
)
